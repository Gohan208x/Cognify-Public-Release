package com.cognify.dto;

public class RewardRequest {
    private int xp;
    private int coins;

    public RewardRequest() {
    }

    public int getXp() {
        return xp;
    }

    public void setXp(int xp) {
        this.xp = xp;
    }

    public int getCoins() {
        return coins;
    }

    public void setCoins(int coins) {
        this.coins = coins;
    }
}
